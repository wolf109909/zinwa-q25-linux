#!/usr/bin/env python3
"""Generate the PipeWire filter-chain for the Q25 speaker from the user's
MediaTek BesLoudness tuning (PlaybackACF/PlaybackDRC 'default' package)."""
import math

def lin(db): return 10 ** (db / 20)

# --- PlaybackACF Speaker (param_id 0): fc/bw/gain(Q24.8 = 1/256 dB) --------
hpf_fc, hpf_order = 0x9F, 4          # 159 Hz, 4th order (2 x 2nd-order, Q 0.71)
lpf_fc = 0x1964                      # 6500 Hz, 1st order
bpf_fc = [0x6B, 0x11C, 0x1F5, 0x3D9, 0x7B1, 0xEED, 0x1356, 0x27C1]
bpf_bw = [0x62, 0xB5, 0xC4, 0x107, 0x133, 0x1A30, 0x3DF, 0x1635]
bpf_gain = [2774, -416, -3719, -3020, -1289, -4608, -1053, -1792]

# --- PlaybackDRC Music: 4-band compressor + limiter (decoded README) --------
xover = [200, 500, 8000]
bands = [  # thresh dB, ratio, attack ms, release ms, knee dB
    (-12.5, 6.2, 10.0, 80.0, 6.0),
    (0.0, 3.0, 10.0, 80.0, 6.0),
    (-22.0, 3.0, 10.0, 80.0, 6.0),
    (-36.0, 3.0, 10.0, 80.0, 9.0),
]
lim_th_db, lim_at, lim_rt = -3.0, 2.0, 60.0

def lpf1(fc, fs):  # 1st-order bilinear low-pass, unity DC gain
    k = math.tan(math.pi * fc / fs)
    b0 = k / (1 + k)
    return dict(b0=b0, b1=b0, b2=0.0, a0=1.0, a1=(k - 1) / (k + 1), a2=0.0)

nodes, links, prev = [], [], None
def add(n, inp="In", out="Out"):
    global prev
    nodes.append(n)
    if prev:
        links.append(f'{{ output = "{prev[0]}:{prev[1]}" input = "{n["name"]}:{inp}" }}')
    prev = (n["name"], out)

for i in range(hpf_order // 2):
    add(dict(name=f"hpf{i}", type="builtin", label="bq_highpass",
             control=dict(Freq=hpf_fc, Q=0.7071)))
coef = ",\n                    ".join(
    "{ rate = %d, b0 = %.10f, b1 = %.10f, b2 = 0.0, a0 = 1.0, a1 = %.10f, a2 = 0.0 }"
    % (fs, c["b0"], c["b1"], c["a1"]) for fs in (44100, 48000, 96000) for c in [lpf1(lpf_fc, fs)])
add(dict(name="lpf", type="builtin", label="bq_raw", raw_coef=coef))
for i, (fc, bw, g) in enumerate(zip(bpf_fc, bpf_bw, bpf_gain)):
    add(dict(name=f"eq{i}", type="builtin", label="bq_peaking",
             control=dict(Freq=fc, Q=round(fc / bw, 3), Gain=round(g / 256, 2))))

mb = {"enabled": 1, "mode": 1, "g_in": 1.0, "g_out": 1.0}
for j in range(1, 8):
    on = j <= len(xover)
    mb[f"cbe_{j}"] = 1 if on else 0
    if on:
        mb[f"sf_{j}"] = xover[j - 1]
for b, (th, cr, at, rt, kn) in enumerate(bands):
    mb.update({f"ce_{b}": 1, f"cm_{b}": 0, f"al_{b}": round(lin(th), 5), f"cr_{b}": cr,
               f"at_{b}": at, f"rt_{b}": rt, f"kn_{b}": round(lin(-kn), 5), f"mk_{b}": 1.0})
add(dict(name="drc", type="lv2", plugin="http://lsp-plug.in/plugins/lv2/mb_compressor_mono",
         control=mb), inp="in", out="out")
add(dict(name="limiter", type="lv2", plugin="http://lsp-plug.in/plugins/lv2/limiter_mono",
         control={"enabled": 1, "alr": 0, "th": round(lin(lim_th_db), 5), "at": lim_at,
                  "rt": min(lim_rt, 20.0), "lk": 5.0, "boost": 0}), inp="in", out="out")

def fmt_node(n):
    s = [f'            {{ type = {n["type"]} name = {n["name"]}']
    s.append(f'              {"label = " + n["label"] if "label" in n else "plugin = \"" + n["plugin"] + "\""}')
    if "raw_coef" in n:
        s.append('              config = { coefficients = [\n                    ' + n["raw_coef"] + '\n              ] }')
    if "control" in n:
        ctl = " ".join(f'"{k}" = {v}' for k, v in n["control"].items())
        s.append(f'              control = {{ {ctl} }}')
    s.append('            }')
    return "\n".join(s)

print(f"""# Zinwa Q25 speaker DSP (generated by tools/audio/gen_q25_dsp.py)
# Source: user's MediaTek BesLoudness tuning "default" (PlaybackACF Speaker +
# PlaybackDRC Music). EQ: PipeWire builtin biquads; DRC + limiter: LSP LV2.
# Inserted by WirePlumber only in front of the Speaker sink (smart filter);
# headphones/earpiece are not processed.
# Deviation: LSP limiter release max is 20 ms (tuning asks 60 ms).
context.modules = [
  {{ name = libpipewire-module-filter-chain
    args = {{
      node.description = "Q25 Speaker DSP"
      media.name       = "Q25 Speaker DSP"
      filter.graph = {{
        nodes = [
{chr(10).join(fmt_node(n) for n in nodes)}
        ]
        links = [
            {chr(10) + "            ".join(links)}
        ]
      }}
      audio.channels = 2
      audio.position = [ FL FR ]
      capture.props = {{
        node.name   = "q25_speaker_dsp"
        media.class = Audio/Sink
        filter.smart = true
        filter.smart.name = "q25-speaker-dsp"
        filter.smart.target = {{ node.name = "alsa_output.platform-mt6789-mt6358-snd.HiFi__Speaker__sink" }}
      }}
      playback.props = {{
        node.name    = "q25_speaker_dsp.output"
        node.passive = true
      }}
    }}
  }}
]""")
